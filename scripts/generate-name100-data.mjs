function normalizeInput(input) {
  return input
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^\w\s]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function aliasesForName(name) {
  const rawLower = name.toLowerCase().trim();
  const normalized = normalizeInput(name);
  const aliases = [rawLower, normalized];
  const parts = normalized.split(' ').filter(Boolean);

  if (parts.length >= 2) {
    aliases.push(parts.at(-1));
    aliases.push(`${parts[0]} ${parts.at(-1)}`);
  }

  return [...new Set(aliases.filter(Boolean))].slice(0, 5);
}

function toAnswer(name, category) {
  const aliases = aliasesForName(name);

  while (aliases.length < 2) {
    aliases.push(aliases[0]);
  }

  return {
    name,
    aliases,
    category,
    hint: categoryHints[category],
  };
}

function dedupeAnswers(answers) {
  const seen = new Set();
  const deduped = [];

  for (const answer of answers) {
    const key = normalizeInput(answer.name);
    if (!key || seen.has(key)) {
      continue;
    }

    seen.add(key);
    deduped.push(answer);
  }

  return deduped;
}

async function buildWomenAnswers() {
  const data = JSON.parse(await readFile(REFERENCE_WOMEN_DB, 'utf8'));
  const names = data.names;

  return dedupeAnswers(
    womenSlices.flatMap(([category, start, count]) =>
      names
        .slice(start, start + count)
        .filter((name) => typeof name === 'string')
        .map((name) => toAnswer(name, category))
    )
  );
}

function buildMenAnswers() {
  return dedupeAnswers(
    Object.entries(menNamesByCategory).flatMap(([category, names]) =>
      names.map((name) => toAnswer(name, category))
    )
  );
}

function summarize(answers) {
  return answers.reduce(
    (summary, answer) => {
      summary.total += 1;
      summary.categories[answer.category] =
        (summary.categories[answer.category] ?? 0) + 1;
      return summary;
    },
    { total: 0, categories: {} }
  );
}

async function main() {
  await mkdir(OUTPUT_DIR, { recursive: true });

  const women = await buildWomenAnswers();
  const men = buildMenAnswers();

  await writeFile(
    new URL('answers-women.json', OUTPUT_DIR),
    `${JSON.stringify(women, null, 2)}\n`
  );
  await writeFile(
    new URL('answers-men.json', OUTPUT_DIR),
    `${JSON.stringify(men, null, 2)}\n`
  );

  console.log(
    JSON.stringify(
      {
        women: summarize(women),
        men: summarize(men),
      },
      null,
      2
    )
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
